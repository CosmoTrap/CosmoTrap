import { expect, test, type Page } from '@playwright/test'

test.setTimeout(120000)
async function start(page: Page) {
  await page.route('**/api/auth.php?action=me', (r) => r.fulfill({ status: 503, contentType: 'application/json', body: '{}' }))
  await page.addInitScript(() => {
    if (!localStorage.getItem('cosmotrap.settings.v1')) localStorage.setItem('cosmotrap.settings.v1', JSON.stringify({ quality: 'low', music: 0, voice: 0, sfx: 0 }))
  })
  await page.goto('/?quality=low')
  await expect(page.getByTestId('launch')).toBeVisible()
  await page.keyboard.press('Space')
  await page.getByTestId('guest').click()
  await page.evaluate(() => { window.__game.start(); window.__game.set({ toured: [1, 2, 3, 4] }) })
  await page.waitForFunction(() => window.__game.state().loading === 1)
}

test('le bras gauche se lève avant la tablette ; plan réel, position, niveaux et zoom', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.setViewportSize({ width: 1280, height: 832 })
  await start(page)
  await page.evaluate(() => window.__game.teleportXZ(44, 41, -Math.PI / 4))
  await page.waitForFunction(() => Math.abs(window.__game.live.pos[0] - 41) < 0.05)
  await page.evaluate(async () => {
    const { _roots } = await import('/node_modules/.vite/deps/@react-three_fiber.js' as string)
    ;(window as any).__scene = _roots.get(document.querySelector('canvas')).store.getState().scene
  })
  await page.keyboard.press('Tab')
  await expect(page.getByTestId('tablet-raising')).toBeVisible()
  await expect(page.getByTestId('tablet')).toBeHidden()
  await page.waitForFunction(() => (window as any).__scene.getObjectByName('tablet-arm-animation').userData.raiseProgress > 0.35)
  const raised = await page.evaluate(() => {
    const s = (window as any).__scene
    return { progress: s.getObjectByName('tablet-arm-animation').userData.raiseProgress, wrist: !!s.getObjectByName('left-wrist-tablet'), arm: !!s.getObjectByName('left-forearm') }
  })
  expect(raised).toMatchObject({ wrist: true, arm: true })
  expect(raised.progress).toBeLessThan(1)
  await page.screenshot({ path: 'test-results/tablet-arm-raising.png' })
  await page.keyboard.down('ArrowUp')
  await expect(page.getByTestId('tablet')).toBeVisible()
  await page.keyboard.up('ArrowUp')
  expect(await page.evaluate(() => window.__game.live.pos[0])).toBeCloseTo(41, 1)
  await expect(page.getByRole('tab')).toHaveCount(4)
  await expect(page.getByTestId('map-player')).toHaveAttribute('data-x', '41.000')
  await expect(page.getByTestId('map-player')).toHaveAttribute('data-z', '41.000')
  await expect(page.getByTestId('map-room-couloir').locator('circle').first()).toHaveAttribute('r', '7')
  await page.getByTestId('map-room-couloir').click()
  await page.screenshot({ path: 'test-results/tablet-plan.png' })
  await page.evaluate(() => window.__game.set({ playTime: 8 }))
  await expect(page.getByTestId('module-power')).toContainText('Secours')
  await page.evaluate(() => window.__game.set({ playTime: 24 }))
  await expect(page.getByTestId('module-power')).toHaveText('En service')
  await page.getByTestId('minimap').hover()
  await page.mouse.wheel(0, -120)
  await expect(page.getByTestId('minimap')).not.toHaveAttribute('data-zoom', '1.00')
  await page.getByTestId('map-level-2').click()
  await expect(page.getByTestId('map-player')).toHaveCount(0)
  await expect(page.getByTestId('map-room-labo')).toBeVisible()
  await expect(page.getByTestId('map-room-dortoir')).toHaveCount(0)
  await page.screenshot({ path: 'test-results/tablet-plan-level2.png' })
  await page.getByTestId('map-room-machinerie').click()
  await expect(page.getByTestId('module-power')).toContainText('Secours')
  await page.evaluate(() => window.__game.set({ flags: { ...window.__game.state().flags, power: true, pw_lights: true } }))
  await expect(page.getByTestId('module-power')).toHaveText('En service')
  await page.keyboard.press('Tab')
  await page.keyboard.down('ArrowUp')
  try { await expect.poll(() => page.evaluate(() => window.__game.live.pos[0])).toBeGreaterThan(41.4) }
  finally { await page.keyboard.up('ArrowUp') }
  expect(errors).toEqual([])
})

test('journal de toutes les missions et historique des transmissions, alertes et documents sauvegardé', async ({ page }) => {
  await start(page)
  await page.evaluate(async () => {
    const { useGame, toast, addNote } = await import('/src/game/state.ts' as string)
    useGame.setState({ subtitle: 'Transmission de contrôle : rejoignez le sas.' })
    useGame.setState({ subtitle: 'Transmission de contrôle : rejoignez le sas.' })
    toast('Alimentation auxiliaire activée.')
    addNote('board')
    useGame.setState({ subtitle: null, flags: { ...useGame.getState().flags, lockerOpen: true } })
  })
  await page.keyboard.press('KeyH')
  await expect(page.getByTestId('mission-journal')).toBeVisible()
  for (const z of [1, 2, 3, 4]) await expect(page.getByTestId(`mission-zone-${z}`)).toHaveCount(1)
  await expect(page.getByTestId('mission-1-locker')).toHaveClass('done')
  await expect(page.getByTestId('mission-2-fuse')).toHaveClass('todo')
  await page.screenshot({ path: 'test-results/tablet-journal.png' })
  await page.getByTestId('tab-2').click()
  await expect(page.getByTestId('message-archive')).toContainText('Alimentation auxiliaire activée.')
  const radio = page.getByTestId('message-archive').getByRole('button').filter({ hasText: 'Transmission de contrôle' })
  await expect(radio).toHaveCount(1)
  await radio.click()
  await expect(page.getByTestId('message-detail')).toContainText('rejoignez le sas')
  await page.screenshot({ path: 'test-results/tablet-messages.png' })
  await page.keyboard.press('Escape')
  const before = await page.evaluate(async () => {
    const { saveGame, G, normalizeSave, saveData } = await import('/src/game/state.ts' as string)
    saveGame(false)
    const legacy = { ...saveData() }; delete legacy.messages
    if (normalizeSave(legacy).messages.length !== 0) throw new Error('Legacy save migration failed')
    return G().messages
  })
  await page.reload()
  await expect(page.getByTestId('launch')).toBeVisible()
  await page.keyboard.press('Space')
  await page.getByTestId('guest').click()
  await page.getByTestId('continue').first().click()
  await page.waitForFunction(() => window.__game.state().loading === 1)
  expect(await page.evaluate(() => window.__game.state().messages)).toEqual(before)
  await page.keyboard.press('Tab')
  await page.getByTestId('tab-2').click()
  await expect(page.getByTestId('message-archive')).toContainText('Alimentation auxiliaire activée.')
})

test('annuler la levée ne réouvre rien ; l’inventaire intégré garde objets, actions et commandes', async ({ page }) => {
  await start(page)
  await page.evaluate(() => { window.__game.give('water', 2); window.__game.give('wrench'); window.__game.give('badge'); window.__game.setRes({ water: 20 }) })
  await page.keyboard.press('KeyI')
  await expect(page.getByTestId('tablet-raising')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.waitForTimeout(1000)
  await expect(page.getByTestId('tablet')).toBeHidden()
  expect(await page.evaluate(() => window.__game.state().tabletReady)).toBe(false)
  await page.keyboard.press('KeyI')
  await expect(page.getByTestId('inventory')).toBeVisible()
  await expect(page.getByTestId('tab-3')).toHaveAttribute('aria-selected', 'true')
  await page.getByTestId('inventory-water').click()
  await page.getByTestId('inventory-use').click()
  expect(await page.evaluate(() => window.__game.state().inv.water)).toBe(1)
  await page.screenshot({ path: 'test-results/tablet-inventory.png' })
  await page.getByTestId('tab-0').click()
  await page.keyboard.press('KeyX')
  expect(await page.evaluate(() => window.__game.state().inv.water)).toBe(1)
  await page.getByTestId('tab-3').click()
  await page.setViewportSize({ width: 844, height: 390 })
  await expect(page.getByTestId('inventory-use')).toBeInViewport()
  await expect(page.getByTestId('close-tablet')).toBeInViewport()
  await page.screenshot({ path: 'test-results/tablet-small.png' })
  await page.getByTestId('close-tablet').click()
  await page.mouse.move(420, 170)
  await page.mouse.wheel(0, 120)
  await expect.poll(() => page.evaluate(() => window.__game.state().selectedItem)).toBe('wrench')
  // Remapping the tablet frees Tab for keyboard navigation within the terminal.
  await page.evaluate(async () => {
    const { useGame } = await import('/src/game/state.ts' as string)
    const settings = useGame.getState().settings
    useGame.setState({ settings: { ...settings, keys: { ...settings.keys, tablet: ['KeyM'] } } })
  })
  await page.keyboard.press('KeyM')
  await expect(page.getByTestId('tablet')).toBeVisible()
  await page.getByTestId('tab-0').focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByTestId('tab-1')).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('Tab')
  await expect(page.getByTestId('close-tablet')).toBeFocused()
  await page.keyboard.press('Space')
  await expect(page.getByTestId('tablet')).toBeHidden()
})
